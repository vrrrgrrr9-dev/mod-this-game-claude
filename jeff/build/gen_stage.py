"""List the stage-decoration objects of game.droid for the void stage (Scyther's SINGULARITY).

usage: gen_stage.py <game.droid> <out stage_decor.h>

The stages draw their scenery with placed instances as well as background/tile layers: o_map_bk
paints the whole backdrop from a 900000-deep instance layer, o_tile_* objects are trees, houses,
grass...  Every object that a battle room (>= 1000 px wide) places on an instance layer deeper
than its "Objects" layer counts as decor.  Controllers, spawn points and characters never do.
The void hides these instances (visible = false: they keep running, colliding and stepping).
"""
import struct, sys

KEEP = {'o_camera', 'o_control_game', 'o_player_control', 'o_survival_spawn1', 'o_survival_spawn2'}
OBJ_PARENT_CHARACTER = 420


def main():
    src, out = sys.argv[1:3]
    D = open(src, 'rb').read()
    u32 = lambda o: struct.unpack_from('<I', D, o)[0]
    i32 = lambda o: struct.unpack_from('<i', D, o)[0]
    ch, p = {}, 8
    while p < len(D):
        ch[D[p:p + 4].decode()] = (p + 8, u32(p + 4)); p += 8 + u32(p + 4)
    st = lambda o: D[o:o + u32(o - 4)].decode('utf8', 'replace') if 0 < o < len(D) else ''
    plist = lambda o: [u32(o + 4 + 4 * i) for i in range(u32(o))]
    objt = plist(ch['OBJT'][0])
    names = [st(u32(q)) for q in objt]
    parent = [i32(q + 28) for q in objt]

    def is_character(i):
        seen = 0
        while 0 <= i < len(names) and seen < 32:
            if i == OBJ_PARENT_CHARACTER:
                return True
            i = parent[i]; seen += 1
        return False

    decor = {}
    for q in plist(ch['ROOM'][0]):
        if u32(q + 8) < 1000:                       # menus and other small rooms
            continue
        room = st(u32(q))
        byid = {u32(g + 12): i32(g + 8) for g in plist(u32(q + 48))}
        layers = plist(u32(q + 92))
        obj_depth = [i32(L + 12) for L in layers if u32(L + 8) == 2 and st(u32(L)) in ('Objects', 'Control_Floor')]
        base = min(obj_depth) if obj_depth else 0
        for L in layers:
            if u32(L + 8) != 2 or i32(L + 12) <= base:
                continue
            for k in range(u32(L + 48)):
                ob = byid.get(u32(L + 52 + 4 * k))
                if ob is None or not 0 <= ob < len(names):
                    continue
                if names[ob] in KEEP or is_character(ob):
                    continue
                decor.setdefault(ob, set()).add(room)
    ids = sorted(decor)
    assert 205 in ids and names[205] == 'o_map_bk', 'o_map_bk (the stage backdrop) not found'
    lines = ['/* generated by build/gen_stage.py from game.droid - stage decoration objects */', '#pragma once',
             f'#define N_STAGE_DECOR {len(ids)}', 'static const short k_stage_decor[N_STAGE_DECOR] = {']
    for i in ids:
        lines.append(f'    {i},   /* {names[i]} */')
    lines.append('};')
    open(out, 'w').write('\n'.join(lines) + '\n')
    print(f'{len(ids)} stage decor objects:', ', '.join(names[i] for i in ids))


if __name__ == '__main__':
    main()
